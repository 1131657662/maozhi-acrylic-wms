import { z } from 'zod';
import {
  masterListQuerySchema,
  masterPageSchema,
  masterItemSchema,
  masterCreateSchema,
  masterCatalogSchema,
  updateMasterItemSchema,
  partyOwnerSchema,
  contactSchema,
  contactListSchema,
  createContactSchema,
  updateContactSchema,
  vehicleSchema,
  vehiclePageSchema,
  createVehicleSchema,
  updateVehicleSchema,
} from '@wms/contracts';
import type { Operation } from '../../openapi.ts';

const routes: Operation[] = [
  {
    method: 'get',
    path: '/{catalog}',
    summary: '分页搜索资料；商品排除条码规格，scope=inventory仅库存资格商品',
    query: masterListQuerySchema,
    response: masterPageSchema,
    channel: 'web',
  },
  {
    method: 'get',
    path: '/{catalog}/{code}',
    summary: '按编码读取资料，含停用项',
    response: masterItemSchema,
    channel: 'web',
  },
  ...masterCatalogSchema.options.map((catalog): Operation => ({
    method: 'post',
    path: `/${catalog}`,
    summary: '新建资料；客户/供应商/仓库禁止传编码，由系统生成；商品/分类手工编码。可选幂等键重放返回原资料',
    body: masterCreateSchema(catalog),
    response: masterItemSchema,
    channel: 'web',
  })),
  {
    method: 'patch',
    path: '/{catalog}/{code}',
    summary: '更新资料；停用检查四类进行中引用，422 data.references返回单号',
    body: updateMasterItemSchema,
    response: masterItemSchema,
    channel: 'web',
  },
  {
    method: 'get',
    path: '/contacts',
    summary: '客户/供应商收送货档案与默认建议',
    query: partyOwnerSchema,
    response: contactListSchema,
    channel: 'web',
  },
  {
    method: 'post',
    path: '/contacts',
    summary: '新增指定往来单位档案；可选 Idempotency-Key，同键同内容返回首次结果，不重复建档',
    body: createContactSchema,
    response: contactSchema,
    channel: 'web',
  },
  {
    method: 'patch',
    path: '/contacts/{id}',
    summary: '修改档案；停用同时清除默认，不改历史快照',
    body: updateContactSchema,
    response: contactSchema,
    channel: 'web',
  },
  {
    method: 'delete',
    path: '/contacts/{id}',
    summary: '仅删除非默认且从未被引用的档案',
    response: z.null(),
    channel: 'web',
  },
  {
    method: 'put',
    path: '/contacts/{id}/default',
    summary: '同归属启用档案设默认，事务中替换唯一默认',
    body: z.strictObject({}),
    response: contactSchema,
    channel: 'web',
  },
  {
    method: 'get',
    path: '/vehicles',
    summary: '按归一化车牌分页查询车辆',
    query: masterListQuerySchema,
    response: vehiclePageSchema,
    channel: 'web',
  },
  { method: 'get', path: '/vehicles/{id}', summary: '读取车辆档案', response: vehicleSchema, channel: 'web' },
  {
    method: 'post',
    path: '/vehicles',
    summary: '手工建档；归一化车牌唯一；可选 Idempotency-Key，同键同内容返回首次结果',
    body: createVehicleSchema,
    response: vehicleSchema,
    channel: 'web',
  },
  {
    method: 'patch',
    path: '/vehicles/{id}',
    summary: '修改司机、电话、备注及启停；不改历史单据车牌',
    body: updateVehicleSchema,
    response: vehicleSchema,
    channel: 'web',
  },
];
export const masterOperations = ['/master', '/master-data'].flatMap((prefix) =>
  routes.map((route) => ({ ...route, path: prefix + route.path })),
);
