import { z } from 'zod';
import {
  createStocktakeSchema,
  publicStocktakeSchema as stocktakeSchema,
  publicStocktakeListSchema as stocktakeListSchema,
  publicStocktakeLinesSchema as stocktakeLinesSchema,
  stocktakeQuerySchema,
  saveReadingSchema,
  publicStocktakeLineSchema as stocktakeLineSchema,
  publicStocktakePreviewSchema as stocktakePreviewSchema,
  stocktakePostSchema,
  voidStocktakeSchema,
  masterItemsSchema,
  revealStocktakeSchema,
  stocktakeExportQuerySchema,
  publicStocktakeDetailSchema,
} from '@wms/contracts';
import type { Operation } from '../../openapi.ts';
import { discoveryOperations } from './discovery-openapi.ts';

export const stocktakeOperations: Operation[] = [
  ...discoveryOperations,
  ...['/stocktake/{id}/reveal', '/stocktakes/{id}/reveal'].map((path): Operation => ({
    method: 'post',
    path,
    summary: '不可逆揭示盲盘账面与差异；不写库存，仅一次审计',
    body: revealStocktakeSchema,
    response: stocktakePreviewSchema,
    channel: 'web',
    idempotent: true,
  })),
  {
    method: 'get',
    path: '/stocktakes/{id}/export',
    summary: '盘点空白或结果 XLSX；未揭示盲盘不含账面与差异',
    query: stocktakeExportQuerySchema,
    response: z.string(),
    channel: 'web',
    responseMedia: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  },
  {
    method: 'get',
    path: '/stocktakes',
    summary: '盘点分页查询；status=counting 为暂停窗口常驻入口',
    query: stocktakeQuerySchema,
    response: stocktakeListSchema,
    channel: 'web',
  },
  {
    method: 'post',
    path: '/stocktakes',
    summary: '生成固定ERP库存快照并持久暂停同仓确认、调整、撤销',
    body: createStocktakeSchema,
    response: stocktakeSchema,
    channel: 'web',
    idempotent: true,
  },
  {
    method: 'get',
    path: '/stocktakes/options/products',
    summary: '按编码或名称查询ERP盘点商品，最多100条',
    query: z.object({ keyword: z.string().max(80).default('') }),
    response: masterItemsSchema,
    channel: 'web',
  },
  {
    method: 'get',
    path: '/stocktakes/{id}',
    summary: '盘点摘要及发现行分页；未揭示盲盘不返回账面',
    query: stocktakeQuerySchema,
    response: publicStocktakeDetailSchema,
    channel: 'web',
  },
  {
    method: 'get',
    path: '/stocktakes/{id}/lines',
    summary: '盘点行服务端分页，最大200行',
    query: stocktakeQuerySchema,
    response: stocktakeLinesSchema,
    channel: 'web',
  },
  {
    method: 'put',
    path: '/stocktakes/{id}/lines/{product}',
    summary: '按行实盘，版本校验及幂等，不改库存',
    body: saveReadingSchema,
    response: stocktakeLineSchema,
    channel: 'web',
    idempotent: true,
  },
  {
    method: 'get',
    path: '/stocktakes/{id}/preview',
    summary: '差异与快照后未入账收发货，token绑定完整清单',
    response: stocktakePreviewSchema,
    channel: 'web',
  },
  {
    method: 'post',
    path: '/stocktakes/{id}/post',
    summary: '人工确认盘点回写，原因必填；未入账默认阻断，显式口径确认留审计；全事务释放窗口',
    body: stocktakePostSchema,
    response: stocktakeSchema,
    channel: 'web',
    idempotent: true,
  },
  {
    method: 'post',
    path: '/stocktakes/{id}/void',
    summary: '作废进行中盘点并释放窗口；不改库存不写流水',
    body: voidStocktakeSchema,
    response: stocktakeSchema,
    channel: 'web',
    idempotent: true,
  },
];
