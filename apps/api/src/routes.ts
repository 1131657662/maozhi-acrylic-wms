import { Router } from 'express';
import type { Database } from './db/mysql.ts';
import { outboundController } from './features/outbound/controller.ts';
import { scanController } from './features/scan/controller.ts';
import { inboundController } from './features/inbound/controller.ts';
import { masterRouter } from './features/master-data/router.ts';
import { outboundPlanController } from './features/outbound/plan-controller.ts';
import { stockRows, auditRows } from './features/outbound/read-models.ts';
import { ok, requireAuth, requireChannel } from './middleware/http.ts';
import { journalQuerySchema } from '@wms/contracts';
import { numberingController } from './features/document-numbering/controller.ts';
import { journalRows } from './features/stock/journal.ts';
import { stockSourceController } from './features/stock/source-controller.ts';
import { stockAdjustmentController } from './features/stock/adjust-controller.ts';
import { catalogRouter } from './features/catalog/router.ts';
import { handoffRouter } from './features/handoff/router.ts';
import { webListRouter } from './features/web-lists/router.ts';
import { webExportRouter } from './features/web-exports/router.ts';
import { lifecycleRouter } from './features/document-lifecycle/router.ts';
import { correctionRouter } from './features/corrections/router.ts';
import { stocktakeRouter } from './features/stocktake/router.ts';
import { reportRouter } from './features/reports/router.ts';
import { listPreferencesRouter } from './features/list-preferences/router.ts';
import { auditRouter, auditOk } from './features/audit/router.ts';

export function businessRouter(db: Database, origins: string[], catalogPublishEnabled = false): Router {
  const router = Router();
  const outbound = outboundController(db);
  const outboundPlans = outboundPlanController(db);
  const inbound = inboundController(db);
  const scan = scanController(db);
  const numbering = numberingController(db);
  const stockSource = stockSourceController(db);
  router.use(requireAuth(db));
  router.use('/web/lists/audit', auditRouter(db, origins));
  router.get('/audit', requireChannel('web', origins), async (_req, res) => auditOk(res, await auditRows(db)));
  router.use('/audit', auditRouter(db, origins));
  router.use(listPreferencesRouter(db, origins));
  router.use(['/master', '/master-data'], masterRouter(db, origins));
  router.use(reportRouter(db, origins));
  router.use(stocktakeRouter(db, origins));
  router.use(lifecycleRouter(db, origins));
  router.use(correctionRouter(db, origins));
  router.use(webListRouter(db, origins));
  router.use(webExportRouter(db, origins));
  router.use(catalogRouter(db, origins, catalogPublishEnabled));
  router.use(handoffRouter(db, origins));
  router.get('/stock/by-source', requireChannel('web', origins), stockSource.stock);
  router.post('/stock/adjustments', requireChannel('web', origins), stockAdjustmentController(db));
  router.get('/stock/by-source/journal', requireChannel('web', origins), stockSource.journal);
  router.get('/document-numbering', requireChannel('web', origins), numbering.list);
  router.put('/document-numbering/:kind', requireChannel('web', origins), numbering.update);
  router.get('/stock/journal', requireChannel('web', origins), async (req, res) =>
    ok(res, await journalRows(db, journalQuerySchema.parse(req.query).limit)),
  );
  router.get('/outbound', outbound.list);
  router.get('/outbound/:id', outbound.detail);
  router.post('/outbound', requireChannel('web', origins), outboundPlans.create);
  router.patch('/outbound/:id', requireChannel('web', origins), outboundPlans.edit);
  router.post('/outbound/:id/confirm', requireChannel('web', origins), outbound.confirm);
  router.get('/inbound', requireChannel('web', origins), inbound.list);
  router.get('/inbound/:id', requireChannel('web', origins), inbound.detail);
  router.post('/inbound', requireChannel('web', origins), inbound.create);
  router.post('/inbound/:id/confirm', requireChannel('web', origins), inbound.confirm);
  router.get('/scan/plans', outbound.list);
  router.get('/scan/plans/:id', outbound.detail);
  router.get('/scan/catalog', scan.catalog);
  router.post('/scan/plans/:id/facts', requireChannel('pda', origins), scan.fact);
  router.post('/scan/plans/:id/submit', requireChannel('pda', origins), scan.freeze);
  router.get('/stock', async (_req, res) => ok(res, await stockRows(db)));
  return router;
}
