CREATE TABLE operation_attempts (
  attempt_id CHAR(36) PRIMARY KEY,
  actor VARCHAR(80) NULL,
  channel VARCHAR(16) NULL,
  action VARCHAR(80) NOT NULL,
  target_kind VARCHAR(32) NULL,
  target_id VARCHAR(100) NULL,
  target_no VARCHAR(80) NULL,
  target_label VARCHAR(160) NULL,
  result VARCHAR(16) NOT NULL,
  effect_state VARCHAR(16) NOT NULL,
  error_code VARCHAR(80) NOT NULL,
  failure_reason VARCHAR(500) NOT NULL,
  trace_id VARCHAR(80) NOT NULL,
  occurred_at DATETIME(3) NOT NULL,
  input_summary JSON NOT NULL,
  CONSTRAINT attempt_channel CHECK(channel IS NULL OR channel IN ('web','pda','miniapp')),
  CONSTRAINT attempt_result CHECK(result IN ('failed','cancelled','unknown')),
  CONSTRAINT attempt_effect CHECK(effect_state IN ('not_applied','unknown')),
  INDEX attempt_time(occurred_at,attempt_id),
  INDEX attempt_action(action,occurred_at,attempt_id),
  INDEX attempt_object(target_kind,target_id,occurred_at,attempt_id),
  INDEX attempt_trace(trace_id,occurred_at,attempt_id)
) ENGINE=InnoDB;

